print('витязь на коне стоит на распутье и смотрит на камень судьбы. у него три пути: налево, направо и прямо.')
choice = input("выберите путь героя: ").strip().lower()

if choice == "налево" or choice == "левый":
    print('налево ехати - богату быти.')
elif choice == "направо" or choice == "правый":
    print('направо ехати - женату быти.')
elif choice == "прямо":
    print('как пряму ехати - живу не бывати - нет пути ни прохожему, ни пролетному')
else:
    print('витязь заблудился и не сделал выбора — время упущено.')